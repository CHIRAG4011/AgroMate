/**
 * AgroMate Camera Manager — OV7670 Implementation
 *
 * OV7670 specifics:
 *   - No hardware JPEG → capture as YUV422, software-convert to JPEG
 *   - XCLK generated via LEDC PWM (independent of LCD_CAM peripheral)
 *   - Resolution: QVGA (320x240) in internal DRAM (no PSRAM)
 */

#include "CameraManager.h"
#include "img_converters.h"
#include <Wire.h>

int CameraManager::begin() {
  // ── Perform Hardware Reset and Power-Up ──
  if (CAM_PIN_PWDN >= 0) {
    pinMode(CAM_PIN_PWDN, OUTPUT);
    digitalWrite(CAM_PIN_PWDN, LOW);
    delay(10);
  }

  if (CAM_PIN_RESET >= 0) {
    Serial.println("[Camera] Performing physical reset pulse...");
    pinMode(CAM_PIN_RESET, OUTPUT);
    digitalWrite(CAM_PIN_RESET, LOW);
    delay(20);
    digitalWrite(CAM_PIN_RESET, HIGH);
    delay(150);
  }

  // Enable internal pull-ups on SCCB (I2C) lines
  pinMode(CAM_PIN_SIOD, INPUT_PULLUP);
  pinMode(CAM_PIN_SIOC, INPUT_PULLUP);
  delay(50);

  // Diagnostic check: verify that I2C lines are pulled HIGH
  if (digitalRead(CAM_PIN_SIOD) == LOW || digitalRead(CAM_PIN_SIOC) == LOW) {
    Serial.println("[Camera] Error: I2C/SCCB pins stuck LOW!");
    return 1;
  }

  // Set camera data and control pins to INPUT_PULLUP before driver init
  pinMode(CAM_PIN_VSYNC, INPUT_PULLUP);
  pinMode(CAM_PIN_HREF, INPUT_PULLUP);
  pinMode(CAM_PIN_PCLK, INPUT_PULLUP);
  for (int pin : {CAM_PIN_D0, CAM_PIN_D1, CAM_PIN_D2, CAM_PIN_D3,
                  CAM_PIN_D4, CAM_PIN_D5, CAM_PIN_D6, CAM_PIN_D7}) {
    pinMode(pin, INPUT_PULLUP);
  }

  // ── Camera driver configuration ──
  // XCLK is generated by the camera driver via LCD_CAM peripheral.
  // pin_xclk MUST be set to the actual pin — the driver uses it to
  // initialize the entire LCD_CAM camera input subsystem (DMA + clock).
  camera_config_t config = {};
  config.ledc_channel = LEDC_CHANNEL_0;
  config.ledc_timer = LEDC_TIMER_0;
  config.pin_d0 = CAM_PIN_D0;
  config.pin_d1 = CAM_PIN_D1;
  config.pin_d2 = CAM_PIN_D2;
  config.pin_d3 = CAM_PIN_D3;
  config.pin_d4 = CAM_PIN_D4;
  config.pin_d5 = CAM_PIN_D5;
  config.pin_d6 = CAM_PIN_D6;
  config.pin_d7 = CAM_PIN_D7;
  config.pin_xclk = CAM_PIN_XCLK;  // Driver manages XCLK + LCD_CAM DMA init
  config.pin_pclk = CAM_PIN_PCLK;
  config.pin_vsync = CAM_PIN_VSYNC;
  config.pin_href = CAM_PIN_HREF;
  config.pin_sccb_sda = CAM_PIN_SIOD;
  config.pin_sccb_scl = CAM_PIN_SIOC;
  config.pin_pwdn = -1;
  config.pin_reset = -1;

  config.xclk_freq_hz = 10000000; // 10MHz — stable for this OV7670 module (20MHz causes green/pink lines)
  config.jpeg_quality = 10;       // Higher quality JPEG (lower = better quality)

#ifdef BOARD_HAS_PSRAM
  config.pixel_format = PIXFORMAT_YUV422;
  config.frame_size = FRAMESIZE_VGA;
  config.fb_location = CAMERA_FB_IN_PSRAM;
  config.fb_count = 2;
  config.grab_mode = CAMERA_GRAB_LATEST;
  Serial.println("[Camera] Configured VGA (640x480) in PSRAM");
#else
  // Color YUV422 (YUYV) at QVGA (320x240)
  // Frame buffer size: 320*240*2 = 153,600 bytes in DRAM
  config.pixel_format = PIXFORMAT_YUV422;
  config.frame_size = FRAMESIZE_QVGA;
  config.fb_location = CAMERA_FB_IN_DRAM;
  config.fb_count = 1;
  config.grab_mode = CAMERA_GRAB_WHEN_EMPTY;
  Serial.println("[Camera] Configured Color YUV422 QVGA (320x240) in DRAM");
#endif

  esp_err_t err = esp_camera_init(&config);
  if (err != ESP_OK) {
    Serial.printf("[Camera] OV7670 init failed: 0x%x\n", err);
    _initialized = false;
    return (int)err;
  }

  // Force internal pull-ups after the driver overrides them
  pinMode(CAM_PIN_VSYNC, INPUT_PULLUP);
  pinMode(CAM_PIN_HREF, INPUT_PULLUP);
  pinMode(CAM_PIN_PCLK, INPUT_PULLUP);
  for (int pin : {CAM_PIN_D0, CAM_PIN_D1, CAM_PIN_D2, CAM_PIN_D3,
                  CAM_PIN_D4, CAM_PIN_D5, CAM_PIN_D6, CAM_PIN_D7}) {
    pinMode(pin, INPUT_PULLUP);
  }

  // ── OV7670 Sensor Settings — Neutral (matching clean reference output) ──
  sensor_t* s = esp_camera_sensor_get();
  if (s) {
      // All adjustments at ZERO/neutral — the OV7670 defaults produce the cleanest output.
      // Boosting contrast/saturation/sharpness on this sensor amplifies noise.
      if (s->set_brightness)     s->set_brightness(s, 0);
      if (s->set_contrast)       s->set_contrast(s, 0);
      if (s->set_saturation)     s->set_saturation(s, 0);

      // Auto White Balance ON for correct colors
      if (s->set_whitebal)       s->set_whitebal(s, 1);
      if (s->set_awb_gain)       s->set_awb_gain(s, 1);

      // Auto Exposure + Auto Gain ON
      if (s->set_exposure_ctrl)  s->set_exposure_ctrl(s, 1);
      if (s->set_gain_ctrl)      s->set_gain_ctrl(s, 1);

      // Normal color mode
      if (s->set_special_effect) s->set_special_effect(s, 0);

      Serial.println("[Camera] OV7670 sensor: neutral settings (AWB+AEC+AGC ON, no boost)");
  }

  _initialized = true;
  Serial.println("[Camera] OV7670 initialized OK (QVGA Color YUV422 @ 10MHz XCLK)");
  return 0;
}

uint8_t *CameraManager::capture(size_t *outSize) {
  lastError = 0;
  lastRawSize = 0;
  
  if (!_initialized) {
    lastError = -1; // Not initialized
    *outSize = 0;
    return nullptr;
  }

  // Release any previously held buffer
  if (_fb) {
    esp_camera_fb_return(_fb);
    _fb = nullptr;
  }

  _fb = esp_camera_fb_get();
  if (!_fb) {
    lastError = 1; // fb_get failed
    Serial.println("[Camera] Frame capture failed!");
    *outSize = 0;
    return nullptr;
  }

  lastRawSize = _fb->len;
  Serial.printf("[Camera] Frame captured: %ux%u, %u bytes (RAW YUV422)\n",
                _fb->width, _fb->height, _fb->len);

  // Return the raw frame buffer buffer directly to save RAM and avoid frame2jpg crashes.
  // The Python backend will convert the raw Grayscale bytes to JPEG.
  *outSize = _fb->len;
  return _fb->buf;
}

camera_fb_t *CameraManager::captureRaw() {
  if (!_initialized)
    return nullptr;
  if (_fb) {
    esp_camera_fb_return(_fb);
    _fb = nullptr;
  }
  _fb = esp_camera_fb_get();
  return _fb;
}

void CameraManager::releaseFrame() {
  if (_fb) {
    esp_camera_fb_return(_fb);
    _fb = nullptr;
  }
  if (_jpgBuf) {
    free(_jpgBuf);
    _jpgBuf = nullptr;
  }
}
