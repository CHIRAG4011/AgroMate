def get_translation(key: str, language: str = "en", **kwargs) -> str:
    """Get a translated string with optional format arguments."""
    translations = TRANSLATIONS.get(key, {})
    text = translations.get(language, translations.get("en", key))

    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, ValueError):
            pass

    return text


def get_language_info(code: str) -> dict:
    """Get language information by code."""
    return SUPPORTED_LANGUAGES.get(code, SUPPORTED_LANGUAGES["en"])


def get_all_languages() -> list[dict]:
    """Get list of all supported languages with metadata for UI display."""
    return [
        {
            "code": code,
            "name": lang["name"],
            "native": lang["native"],
            "script": lang.get("script", ""),
            "rtl": lang.get("rtl", False),
            "has_tts": "fallback_tts" not in lang,
            "has_stt": bool(lang.get("vosk_model")),
        }
        for code, lang in SUPPORTED_LANGUAGES.items()
    ]


def get_tts_voice(language: str, gender: str = "female") -> str:
    """Get the TTS voice name for a given language and gender."""
    lang_info = SUPPORTED_LANGUAGES.get(language, SUPPORTED_LANGUAGES["en"])
    if gender == "male":
        return lang_info.get("tts_voice_male", lang_info["tts_voice"])
    return lang_info["tts_voice"]


def get_google_stt_code(language: str) -> str:
    """Get the Google Speech Recognition language code."""
    lang_info = SUPPORTED_LANGUAGES.get(language, SUPPORTED_LANGUAGES["en"])
    return lang_info.get("google_stt_code", "en-IN")


def is_rtl(language: str) -> bool:
    """Check if a language uses right-to-left script."""
    lang_info = SUPPORTED_LANGUAGES.get(language, {})
    return lang_info.get("rtl", False)


def get_all_translations(language: str) -> dict:
    """Get all translations for a given language — used by frontend i18n."""
    result = {}
    for key, translations in TRANSLATIONS.items():
        result[key] = translations.get(language, translations.get("en", key))
    return result


